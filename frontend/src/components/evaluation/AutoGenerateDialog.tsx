import { useState, useEffect, useRef } from 'react'
import {
  Dialog,
  DialogContent,
  DialogHeader,
  DialogTitle,
  DialogFooter,
} from '@/components/ui/dialog'
import { Button } from '@/components/ui/button'
import { Label } from '@/components/ui/label'
import { Input } from '@/components/ui/input'
import { Checkbox } from '@/components/ui/checkbox'
import { PromptConfigEditor } from '@/components/shared/PromptConfigEditor'
import { useDocuments } from '@/hooks/useDocuments'
import { DEFAULT_GENERATION_SYSTEM_PROMPT } from '@/constants/golden-set-generation'
import * as api from '@/api/golden-sets'
import type { PromptConfig } from '@/types/prompt-config'
import type { QuestionType } from '@/types/golden-set'

type DialogStep = 'config' | 'progress' | 'complete'

interface AutoGenerateDialogProps {
  open: boolean
  onOpenChange: (open: boolean) => void
  projectId: string
  goldenSetId: string
  initialQueryCount: number
  onComplete: () => void
}

const QUESTION_TYPES: { value: QuestionType; label: string }[] = [
  { value: 'factual', label: 'Factual' },
  { value: 'comparison', label: 'Comparison' },
  { value: 'summarization', label: 'Summarization' },
]

export function AutoGenerateDialog({
  open,
  onOpenChange,
  projectId,
  goldenSetId,
  initialQueryCount,
  onComplete,
}: AutoGenerateDialogProps) {
  const { documents } = useDocuments(projectId, 'ready')

  const [step, setStep] = useState<DialogStep>('config')
  const [documentIds, setDocumentIds] = useState<string[]>([])
  const [queriesPerDocument, setQueriesPerDocument] = useState(5)
  const [questionTypes, setQuestionTypes] = useState<QuestionType[]>(['factual'])
  const [promptConfig, setPromptConfig] = useState<PromptConfig>({
    provider: 'openai',
    model: 'gpt-4o',
    temperature: 0.7,
    systemPrompt: DEFAULT_GENERATION_SYSTEM_PROMPT,
  })
  const [progress, setProgress] = useState<{ completed: number; total: number } | null>(null)
  const [generatedCount, setGeneratedCount] = useState(0)
  const [error, setError] = useState<string | null>(null)
  const pollRef = useRef<ReturnType<typeof setInterval> | null>(null)

  useEffect(() => {
    if (open) {
      setStep('config')
      setDocumentIds([])
      setQueriesPerDocument(5)
      setQuestionTypes(['factual'])
      setPromptConfig({
        provider: 'openai',
        model: 'gpt-4o',
        temperature: 0.7,
        systemPrompt: DEFAULT_GENERATION_SYSTEM_PROMPT,
      })
      setProgress(null)
      setGeneratedCount(0)
      setError(null)
    }
    return () => {
      if (pollRef.current) clearInterval(pollRef.current)
    }
  }, [open])

  const canGenerate = documentIds.length > 0 && questionTypes.length > 0

  const toggleDocument = (id: string) => {
    setDocumentIds((prev) =>
      prev.includes(id) ? prev.filter((d) => d !== id) : [...prev, id]
    )
  }

  const toggleQuestionType = (type: QuestionType) => {
    setQuestionTypes((prev) =>
      prev.includes(type) ? prev.filter((t) => t !== type) : [...prev, type]
    )
  }

  const handleGenerate = async () => {
    setStep('progress')
    setProgress({ completed: 0, total: 0 })

    try {
      await api.generateGoldenSet(projectId, goldenSetId, {
        documentIds,
        llmProvider: promptConfig.provider ?? 'openai',
        llmModel: promptConfig.model ?? 'gpt-4o',
        queriesPerDocument,
        questionTypes,
        temperature: promptConfig.temperature ?? 0.7,
        systemPrompt: promptConfig.systemPrompt || undefined,
      })

      pollRef.current = setInterval(async () => {
        try {
          const gs = await api.getGoldenSet(projectId, goldenSetId)
          const prog = gs.generationProgress
          if (prog) {
            setProgress({ completed: prog.completedWindows, total: prog.totalWindows })
          }

          if (gs.generationStatus === 'completed') {
            clearInterval(pollRef.current!)
            const newCount = Math.max(0, gs.queries.length - initialQueryCount)
            setGeneratedCount(newCount)
            setStep('complete')
            onComplete()
          } else if (gs.generationStatus === 'failed') {
            clearInterval(pollRef.current!)
            const newCount = Math.max(0, gs.queries.length - initialQueryCount)
            setGeneratedCount(newCount)
            setError(prog?.errorMessage ?? 'Generation failed.')
            setStep('complete')
            onComplete()
          }
        } catch {
          // ignore transient poll errors
        }
      }, 2500)
    } catch (err) {
      setError(err instanceof Error ? err.message : 'Failed to start generation.')
      setStep('complete')
    }
  }

  const handleDone = () => {
    onOpenChange(false)
  }

  return (
    <Dialog
      open={open}
      onOpenChange={(v) => {
        if (step === 'progress') return
        onOpenChange(v)
      }}
    >
      <DialogContent className="max-w-lg max-h-[90vh] overflow-y-auto">
        <DialogHeader>
          <DialogTitle>Auto-Generate Queries</DialogTitle>
        </DialogHeader>

        {step === 'config' && (
          <div className="space-y-5">
            {/* Documents */}
            <div className="space-y-2">
              <Label>Documents</Label>
              {documents.length === 0 ? (
                <p className="text-sm text-muted-foreground">No ready documents found.</p>
              ) : (
                <div className="space-y-1.5 max-h-40 overflow-y-auto border rounded-md p-2">
                  {documents.map((doc) => (
                    <div key={doc.id} className="flex items-center gap-2">
                      <Checkbox
                        id={`doc-${doc.id}`}
                        checked={documentIds.includes(doc.id)}
                        onCheckedChange={() => toggleDocument(doc.id)}
                      />
                      <label htmlFor={`doc-${doc.id}`} className="text-sm cursor-pointer">
                        {doc.title}
                      </label>
                    </div>
                  ))}
                </div>
              )}
            </div>

            {/* Queries per document */}
            <div className="space-y-1.5">
              <Label htmlFor="qpd">Queries per document</Label>
              <Input
                id="qpd"
                type="number"
                min={1}
                max={30}
                value={queriesPerDocument}
                onChange={(e) => setQueriesPerDocument(Math.max(1, Math.min(30, Number(e.target.value))))}
                className="w-24"
              />
            </div>

            {/* Question types */}
            <div className="space-y-1.5">
              <Label>Question types</Label>
              <div className="flex gap-4">
                {QUESTION_TYPES.map(({ value, label }) => (
                  <div key={value} className="flex items-center gap-2">
                    <Checkbox
                      id={`qt-${value}`}
                      checked={questionTypes.includes(value)}
                      onCheckedChange={() => toggleQuestionType(value)}
                    />
                    <label htmlFor={`qt-${value}`} className="text-sm cursor-pointer">{label}</label>
                  </div>
                ))}
              </div>
            </div>

            {/* LLM Configuration */}
            <div className="space-y-2">
              <Label>LLM Configuration</Label>
              <PromptConfigEditor
                value={promptConfig}
                onChange={setPromptConfig}
              />
              <button
                type="button"
                className="text-xs text-muted-foreground underline underline-offset-2 hover:text-foreground"
                onClick={() => setPromptConfig((p) => ({ ...p, systemPrompt: DEFAULT_GENERATION_SYSTEM_PROMPT }))}
              >
                Reset to default prompt
              </button>
            </div>

            <DialogFooter>
              <Button variant="outline" onClick={() => onOpenChange(false)}>
                Cancel
              </Button>
              <Button onClick={handleGenerate} disabled={!canGenerate}>
                Generate
              </Button>
            </DialogFooter>
          </div>
        )}

        {step === 'progress' && (
          <div className="space-y-4 py-4">
            <p className="text-sm text-center text-muted-foreground">
              {progress
                ? `${progress.completed} / ${progress.total || '?'} windows processed`
                : 'Starting generation…'}
            </p>
            <div className="h-2 rounded-full bg-muted overflow-hidden">
              <div
                className="h-full rounded-full bg-primary transition-all duration-500"
                style={{
                  width: progress && progress.total > 0
                    ? `${Math.round((progress.completed / progress.total) * 100)}%`
                    : '0%',
                }}
              />
            </div>
            <p className="text-xs text-center text-muted-foreground">
              This may take a minute. Please wait.
            </p>
          </div>
        )}

        {step === 'complete' && (
          <div className="space-y-4 py-4 text-center">
            {error ? (
              <>
                <p className="text-sm text-destructive">{error}</p>
                {generatedCount > 0 && (
                  <p className="text-sm text-muted-foreground">
                    {generatedCount} {generatedCount === 1 ? 'query was' : 'queries were'} created before the failure.
                  </p>
                )}
              </>
            ) : (
              <p className="text-sm font-medium">
                Generated {generatedCount} {generatedCount === 1 ? 'query' : 'queries'}.
              </p>
            )}
            <DialogFooter className="justify-center">
              <Button onClick={handleDone}>Done</Button>
            </DialogFooter>
          </div>
        )}
      </DialogContent>
    </Dialog>
  )
}
