import { render, screen, fireEvent } from '@testing-library/react'
import { vi, test, expect } from 'vitest'
import { AutoGenerateDialog } from './AutoGenerateDialog'

vi.mock('@/hooks/useDocuments', () => ({
  useDocuments: () => ({
    documents: [
      { id: 'doc1', title: 'Annual Report 2024', status: 'ready' },
    ],
    isLoading: false,
  }),
}))

test('Generate button is disabled when no document selected', () => {
  render(
    <AutoGenerateDialog
      open={true}
      onOpenChange={vi.fn()}
      projectId="proj1"
      goldenSetId="gs1"
      initialQueryCount={0}
      onComplete={vi.fn()}
    />
  )
  expect(screen.getByRole('button', { name: /generate/i })).toBeDisabled()
})

test('Generate button is disabled when no question type selected', () => {
  render(
    <AutoGenerateDialog
      open={true}
      onOpenChange={vi.fn()}
      projectId="proj1"
      goldenSetId="gs1"
      initialQueryCount={0}
      onComplete={vi.fn()}
    />
  )
  const factual = screen.getByRole('checkbox', { name: /factual/i })
  fireEvent.click(factual)
  expect(screen.getByRole('button', { name: /generate/i })).toBeDisabled()
})

test('system prompt is pre-populated with default', () => {
  render(
    <AutoGenerateDialog
      open={true}
      onOpenChange={vi.fn()}
      projectId="proj1"
      goldenSetId="gs1"
      initialQueryCount={0}
      onComplete={vi.fn()}
    />
  )
  expect(screen.getByDisplayValue(/evaluation queries/i)).toBeInTheDocument()
})
