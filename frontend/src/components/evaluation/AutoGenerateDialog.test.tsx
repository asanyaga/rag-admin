import { render, screen, fireEvent } from '@testing-library/react'
import { AutoGenerateDialog } from './AutoGenerateDialog'

vi.mock('@/hooks/useDocuments', () => ({
  useDocuments: () => ({
    documents: [
      { id: 'doc1', title: 'Annual Report 2024', status: 'ready' },
    ],
    isLoading: false,
  }),
}))

test('Generate button is disabled when no document selected', () => {
  render(
    <AutoGenerateDialog
      open={true}
      onOpenChange={vi.fn()}
      projectId="proj1"
      goldenSetId="gs1"
      initialQueryCount={0}
      onComplete={vi.fn()}
    />
  )
  expect(screen.getByRole('button', { name: /generate/i })).toBeDisabled()
})

test('Generate button is disabled when no question type selected', () => {
  render(
    <AutoGenerateDialog
      open={true}
      onOpenChange={vi.fn()}
      projectId="proj1"
      goldenSetId="gs1"
      initialQueryCount={0}
      onComplete={vi.fn()}
    />
  )
  // Uncheck all question types
  const factual = screen.getByRole('checkbox', { name: /factual/i })
  fireEvent.click(factual) // uncheck the default-checked Factual
  expect(screen.getByRole('button', { name: /generate/i })).toBeDisabled()
})

test('system prompt textarea is pre-populated with default', () => {
  render(
    <AutoGenerateDialog
      open={true}
      onOpenChange={vi.fn()}
      projectId="proj1"
      goldenSetId="gs1"
      initialQueryCount={0}
      onComplete={vi.fn()}
    />
  )
  const textarea = screen.getByPlaceholderText(/using default generation prompt/i)
  expect((textarea as HTMLTextAreaElement).value).toContain('evaluation queries')
})
